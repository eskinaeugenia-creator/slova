# Проверка уровня: карточка на «Сегодня», 10 слов «знаю / не знаю», уровень 1–5, советы, Настройки, пропуск
import os
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
SH=os.environ.get('SHOTS', '/home/claude/tests/shots/')
def run(pg, answers):
    pg.wait_for_selector('#level-word')
    for a in answers:
        n=pg.locator('#level-count').inner_text()
        pg.click('#level-yes' if a else '#level-no')
        pg.wait_for_function("n => !document.querySelector('#level-count') || document.querySelector('#level-count').textContent !== n", arg=n)
    pg.wait_for_selector('#level-result')
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':375,'height':740}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    ok('при первом запуске предложена проверка уровня', pg.locator('#level-offer').count()==1)
    ok('пустой словарь по-прежнему предлагает готовый набор', pg.locator('text=Начать с готового набора').count()==1)
    pg.click('#level-go'); pg.wait_for_selector('#level-word')
    ok('счётчик 1/10', pg.locator('#level-count').inner_text()=='1/10')
    first=pg.locator('#level-word').inner_text()
    pg.click('#level-yes'); pg.wait_for_function("document.querySelector('#level-count').textContent==='2/10'")
    ok('первые слова простые', first in ['cat','water','house','mother','sun','book','red','eat'], first)
    pg.screenshot(path=SH+'level-card.png')
    # 1 уже «знаю», ещё 5 «знаю» (итого 6) и 4 «не знаю» → уровень 3
    run(pg, [True]*5 + [False]*4)
    lv=pg.evaluate("App.S.settings.level")
    ok('6 из 10 → уровень 3', lv==3, lv)
    ok('уровень показан словами', 'Уровень 3 из 5' in pg.locator('#level-n').inner_text() and 'A2' in pg.locator('#level-n').inner_text())
    ok('советы: наборы, книги, диалоги, грамматика', all(pg.locator(s).count()>0 for s in ['.lv-set','.lv-book','.lv-dialog','.lv-gram']))
    ok('книги и диалоги своего уровня', 'уровень 3' in pg.locator('.lv-book').first.inner_text() and 'уровень 3' in pg.locator('.lv-dialog').first.inner_text())
    ok('список «проверьте себя» с переводами', pg.locator('#level-words .row').count()==10)
    pg.screenshot(path=SH+'level-result.png', full_page=True)
    ok('нет горизонтальной прокрутки', pg.evaluate("document.documentElement.scrollWidth <= innerWidth"))
    pg.locator('.lv-set').first.click(); pg.wait_for_selector('.witem')
    ok('совет-набор открывает набор', 'Добавить' in pg.locator('.savebar .btn').inner_text())
    pg.goto(BASE+'#today'); pg.wait_for_selector('h1')
    ok('после проверки карточка на «Сегодня» не показывается', pg.locator('#level-offer').count()==0)
    pg.reload(); pg.wait_for_selector('h1')
    ok('уровень сохранён после перезапуска', pg.evaluate("App.S.settings.level")==3)
    pg.goto(BASE+'#prefs'); pg.wait_for_selector('#level-prefs')
    ok('в Настройках виден уровень', 'Уровень 3 из 5' in pg.locator('#level-prefs').inner_text())
    pg.click('#level-again'); run(pg, [True]*10)
    ok('пройти заново: 10 из 10 → уровень 5', pg.evaluate("App.S.settings.level")==5)
    pg.click('#level-retry'); run(pg, [False]*10)
    ok('0 из 10 → уровень 1, советы для начинающих', pg.evaluate("App.S.settings.level")==1 and 'уровень 1' in pg.locator('.lv-book').first.inner_text())
    # Пропуск — в новом профиле
    ctx2=b.new_context(viewport={'width':320,'height':640}); pg2=ctx2.new_page(); pg2.on('pageerror', lambda e: errs.append(str(e)))
    pg2.goto(BASE); pg2.wait_for_selector('#level-offer'); pg2.click('#level-skip'); pg2.wait_for_timeout(300)
    ok('«Пропустить» убирает карточку', pg2.locator('#level-offer').count()==0)
    pg2.reload(); pg2.wait_for_selector('h1'); pg2.wait_for_timeout(300)
    ok('после перезапуска карточка не возвращается', pg2.locator('#level-offer').count()==0)
    pg2.goto(BASE+'#prefs'); pg2.wait_for_selector('#level-prefs')
    ok('в Настройках можно пройти проверку', pg2.locator('#level-again').inner_text()=='Пройти проверку')
    ok('нет ошибок на странице', not errs, errs)
