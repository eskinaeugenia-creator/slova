# Картинка скрыта, пока не вспомнишь: «Карточка» и «Напишите по-английски»
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
def start(pg, typ, en, ru, emoji):
    pg.evaluate(f"(async()=>{{ const w=App.newWord({{en:'{en}',ru:'{ru}',emoji:'{emoji}'}}); w.srs.recog=Core.review(null,3,Date.now()-86400000*2); w.srs.recall=Core.review(null,3,Date.now()-86400000*2); await App.saveWord(w); Train.startPrep({{wordIds:[w.id], types:['{typ}']}}); }})()")
def picVisible(pg): return pg.evaluate("(() => { const p=document.querySelector('.sbody .prompt .pic'); return !!p && !p.hidden && p.offsetParent!==null; })()")
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}); ctx.add_init_script(FAKE_TTS)
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    ok('по умолчанию «Показывать картинку сразу» выключено', pg.evaluate("App.S.settings.picFirst===false"))
    # Карточка
    start(pg,'flash','umbrella','зонт','☂️'); pg.wait_for_selector('text=Показать ответ')
    ok('карточка: картинка скрыта до ответа', not picVisible(pg))
    ok('карточка: есть кнопка «Подсказка: картинка»', pg.locator('text=Подсказка: картинка').count()==1)
    pg.click('text=Подсказка: картинка'); pg.wait_for_timeout(150)
    ok('карточка: по кнопке картинка показана, кнопка исчезла', picVisible(pg) and pg.locator('text=Подсказка: картинка').count()==0)
    pg.evaluate("Train.abort(true)"); pg.wait_for_timeout(200)
    start(pg,'flash','apple','яблоко','🍎'); pg.wait_for_selector('text=Показать ответ')
    pg.click('text=Показать ответ'); pg.wait_for_timeout(150)
    ok('карточка: после «Показать ответ» картинка видна', picVisible(pg))
    pg.evaluate("Train.abort(true)"); pg.wait_for_timeout(200)
    # Напишите по-английски
    start(pg,'ruEn','cat','кошка','🐈'); pg.wait_for_selector('.sbody input')
    ok('письмо: картинка скрыта до ответа', not picVisible(pg))
    ok('письмо: есть кнопка «Подсказка: картинка»', pg.locator('text=Подсказка: картинка').count()==1)
    inp=pg.locator('.sbody input').first; inp.fill('cat'); inp.press('Enter'); pg.wait_for_selector('.feedback.ok')
    ok('письмо: после ответа картинка видна', picVisible(pg) and pg.locator('text=Подсказка: картинка').count()==0)
    pg.evaluate("Train.abort(true)"); pg.wait_for_timeout(200)
    start(pg,'ruEn','dog','собака','🐕'); pg.wait_for_selector('.sbody input')
    pg.click('text=Не знаю'); pg.wait_for_selector('.feedback.no')
    ok('письмо: после «Не знаю» картинка видна', picVisible(pg))
    pg.evaluate("Train.abort(true)"); pg.wait_for_timeout(200)
    # Настройка «сразу»
    pg.evaluate("location.hash='prefs'"); pg.wait_for_selector('text=Показывать картинку сразу')
    pg.click('label.switch:has-text("Показывать картинку сразу")'); pg.wait_for_timeout(200)
    ok('настройка включается', pg.evaluate("App.S.settings.picFirst===true"))
    start(pg,'flash','house','дом','🏠'); pg.wait_for_selector('text=Показать ответ')
    ok('при «сразу» картинка видна в карточке и кнопки нет', picVisible(pg) and pg.locator('text=Подсказка: картинка').count()==0)
    pg.evaluate("Train.abort(true)"); pg.wait_for_timeout(200)
    start(pg,'ruEn','car','машина','🚗'); pg.wait_for_selector('.sbody input')
    ok('при «сразу» картинка видна в письме', picVisible(pg))
    pg.screenshot(path='/tmp/claude-0/-home-claude-slova/5855c74e-bb62-50bd-b378-099184c5c093/scratchpad/hidepic.png')
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
    b.close()
import sys; sys.exit(0 if all(res) else 1)
