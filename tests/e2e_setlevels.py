# Готовые наборы: метки уровня A0–B1, фильтр по уровню, новые наборы A0–A1
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
import os, tempfile
SH = tempfile.gettempdir() + '/'
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True, device_scale_factor=2)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    data=pg.evaluate("ReadySets.map(s=>({id:s.id,level:s.level,n:s.words.length,bad:s.words.filter(w=>!w.en||!w.ru||!w.example||!w.exampleRu||!w.emoji).length}))")
    ok('у каждого набора есть уровень', all(d['level'] in ('A0','A1','A2','B1') for d in data), [d for d in data if d['level'] not in ('A0','A1','A2','B1')])
    ok('у всех слов есть перевод, пример и эмодзи', all(d['bad']==0 for d in data))
    ids={d['id'] for d in data}
    ok('новые наборы A0–A1 на месте', {'verbs1','verbs2','opposites','questions','food','animals','nature','places'} <= ids)
    ok('в новых наборах по 15–25 слов', all(15 <= d['n'] <= 25 for d in data if d['id'] in ('verbs1','verbs2','opposites','questions','food','animals','nature','places')))
    dup=pg.evaluate("ReadySets.filter(s=>new Set(s.words.map(w=>Core.keyEn(w.en))).size!==s.words.length).map(s=>s.id)")
    ok('внутри набора слова не повторяются', not dup, dup)
    pg.goto(BASE+'#sets'); pg.wait_for_selector('.set-tile')
    total=pg.locator('.set-tile').count()
    ok('на экране все наборы', total==len(data), total)
    ok('есть фильтр Все / A0 / A1 / A2', pg.locator('#sets-levels .chip').count()>=4 and pg.locator('#sets-levels [data-level=A0]').count()==1)
    ok('на плитке видна метка уровня', 'A0 ·' in pg.locator('.set-tile').first.inner_text(), pg.locator('.set-tile').first.inner_text())
    pg.click('#sets-levels [data-level=A0]'); pg.wait_for_timeout(200)
    n0=sum(1 for d in data if d['level']=='A0')
    txt=pg.evaluate("[...document.querySelectorAll('.set-tile small')].map(x=>x.textContent)")
    ok('фильтр A0 оставляет только A0', len(txt)==n0 and all(t.startswith('A0') for t in txt), (len(txt), n0))
    ok('кнопка A0 нажата', pg.locator('#sets-levels [data-level=A0]').get_attribute('aria-pressed')=='true')
    pg.screenshot(path=SH+'sets-levels.png')
    pg.click('#sets-levels [data-level=A2]'); pg.wait_for_timeout(200)
    ok('фильтр A2 показывает «Аренда жилья»', pg.locator('.set-tile').count()==sum(1 for d in data if d['level']=='A2') and 'Аренда' in pg.locator('.set-tile').first.inner_text())
    # фильтр запоминается при возврате
    pg.goto(BASE+'#set-animals'); pg.wait_for_selector('text=Добавить в словарь')
    ok('на экране набора указан уровень', 'Уровень A0' in pg.locator('#set-level').inner_text())
    pg.click('text=Добавить в словарь'); pg.wait_for_timeout(600)
    n=pg.evaluate("[...App.S.words.values()].length")
    ok('слова набора «Животные» добавились', n==20, n)
    pg.goto(BASE+'#sets'); pg.wait_for_selector('#sets-levels')
    ok('выбранный уровень запомнился', pg.locator('#sets-levels [data-level=A2]').get_attribute('aria-pressed')=='true')
    pg.click('#sets-levels [data-level=all]'); pg.wait_for_timeout(200)
    full=pg.locator('.set-tile.full')
    ok('«Животные» внизу с отметкой «В словаре»', full.count()==1 and 'Животные' in full.inner_text())
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
