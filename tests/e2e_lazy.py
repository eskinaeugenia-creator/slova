# Скорость загрузки: книги и диалоги (books-data.js) грузятся только при открытии полки / диалогов; офлайн тоже работает
import os
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
SH=os.environ.get('SHOTS', '/tmp/')
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    reqs=[]; pg.on('request', lambda r: reqs.append(r.url))
    pg.goto(BASE); pg.wait_for_selector('h1'); pg.wait_for_timeout(800)
    ok('на «Сегодня» книги не загружены', pg.evaluate("!window.BOOKS") and not any('books-data' in u for u in reqs), [u for u in reqs if 'books-data' in u])
    pg.goto(BASE+'#train'); pg.wait_for_selector('h1'); pg.wait_for_timeout(300)
    ok('в «Тренировках» книги тоже не грузятся', pg.evaluate("!window.BOOKS"))
    pg.goto(BASE+'#books'); pg.wait_for_selector('text=Книжная полка'); pg.wait_for_timeout(500)
    ok('полка открылась и книги подгрузились', pg.evaluate("Array.isArray(window.BOOKS) && BOOKS.length > 5"), pg.evaluate("(window.BOOKS||[]).length"))
    ok('на полке есть книги', 'Little Red Hen' in pg.locator('main').inner_text())
    n=sum('books-data' in u for u in reqs)
    pg.goto(BASE+'#dialogs'); pg.wait_for_selector('h1'); pg.wait_for_timeout(500)
    ok('файл книг не грузится повторно', sum('books-data' in u for u in reqs)==n, n)
    # прямая ссылка сразу на диалог (как из «Мой уровень») — после перезагрузки
    pg.goto(BASE+'#today'); pg.reload(); pg.wait_for_selector('h1')
    pg.goto(BASE+'#dialog-meet1'); pg.wait_for_timeout(1500)
    ok('прямая ссылка на диалог открывается', pg.evaluate("!!window.DIALOGS") and 'Загрузка' not in pg.locator('h1').inner_text(), pg.locator('h1').inner_text())
    pg.goto(BASE+'#today'); pg.reload(); pg.wait_for_selector('h1')
    pg.goto(BASE+'#read-hen-0'); pg.wait_for_timeout(1500)
    ok('прямая ссылка на чтение книги открывается', 'little red hen' in pg.locator('main').inner_text().lower(), pg.locator('main').inner_text()[:120])
    # офлайн: книги берутся из кэша
    sw = pg.evaluate("navigator.serviceWorker && navigator.serviceWorker.controller ? 'active' : 'none'")
    if sw == 'none': pg.reload(); pg.wait_for_timeout(1500)
    pg.goto(BASE+'#today'); pg.wait_for_timeout(1500)
    ctx.set_offline(True)
    pg.reload(); pg.wait_for_selector('h1')
    ok('офлайн: книги ещё не загружены после перезапуска', pg.evaluate("!window.BOOKS"))
    pg.goto(BASE+'#books'); pg.wait_for_timeout(1500)
    ok('офлайн: полка открывается из кэша', 'Little Red Hen' in pg.locator('main').inner_text(), pg.locator('main').inner_text()[:120])
    pg.screenshot(path=SH+'lazy-offline.png')
    ctx.set_offline(False)
    # ошибка загрузки — понятное сообщение и кнопка «Ещё раз»
    ctx2=b.new_context(viewport={'width':390,'height':800}); pg2=ctx2.new_page()
    ctx2.route('**/js/books-data.js*', lambda r: r.abort())
    pg2.goto(BASE+'#books'); pg2.wait_for_timeout(1500)
    ok('без файла книг — сообщение и «Ещё раз»', 'Не получилось загрузить книги' in pg2.locator('main').inner_text() and pg2.locator('button:has-text("Ещё раз")').count()==1, pg2.locator('main').inner_text()[:150])
    ctx2.unroute('**/js/books-data.js*'); pg2.click('button:has-text("Ещё раз")'); pg2.wait_for_timeout(1500)
    ok('«Ещё раз» открывает полку', 'Little Red Hen' in pg2.locator('main').inner_text())
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
