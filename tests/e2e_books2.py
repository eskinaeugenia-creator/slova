# Новые книги уровней 1–2: на полке, нажатие на слово (формы глаголов), перевод абзаца, главы басен
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://api.mymemory.translated.net/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.goto(BASE+'#books'); pg.wait_for_selector('.tile.wide')
    titles=pg.locator('.tile.wide b').all_inner_texts()
    new=['The Gingerbread Man','The Enormous Turnip','The Town Mouse and the Country Mouse','More Fables','The Ugly Duckling']
    ok('5 новых книг на полке', all(t in titles for t in new), titles)
    ok('уровни 1–2 идут перед уровнем 3', titles.index('The Ugly Duckling') < titles.index('The Elves and the Shoemaker'))
    pg.click('.tile.wide:has-text("The Enormous Turnip")'); pg.wait_for_selector('.rw')
    ok('одна глава — сразу чтение', 'read-turnip-0' in pg.url)
    pg.locator('.rw', has_text='pulls').first.click(); pg.wait_for_selector('.sheet')
    ok('pulls → pull, тянуть', 'тянуть' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.locator('.rp-tools button:has-text("Перевод")').first.click(); pg.wait_for_timeout(200)
    ok('свой перевод абзаца без интернета', 'Дед сажает репку' in pg.locator('.rp-tr').first.inner_text())
    pg.goto(BASE+'#book-fables2'); pg.wait_for_selector('.tile.wide')
    ok('«More Fables»: 3 басни', pg.locator('.tile.wide').count()==3)
    pg.goto(BASE+'#read-fables2-2'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='blew').first.click(); pg.wait_for_selector('.sheet')
    ok('blew → blow, дуть', 'дуть' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.goto(BASE+'#read-duckling-0'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='swans').first.click(); pg.wait_for_selector('.sheet')
    ok('swans → swan, лебедь', 'лебедь' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    n_q=pg.locator('.options').count()
    ok('после «Гадкого утёнка» 3 вопроса', n_q==3)
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
