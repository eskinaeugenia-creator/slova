# Аудиокнига: «Слушать книгу», главы подряд, скорость, пауза, перемотка, продолжение с места остановки
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
WAKE = """(() => { window.__wake = 0; Object.defineProperty(navigator, 'wakeLock', { configurable: true, value: { request: async () => { window.__wake++; return { release: async () => { window.__wake--; }, addEventListener(){} }; } } }); })();"""
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS); ctx.add_init_script(WAKE)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    # кнопка на экране книги с главами
    pg.goto(BASE+'#book-peter'); pg.wait_for_selector('#ab-open')
    ok('на экране книги кнопка «Слушать книгу»', 'Слушать книгу' in pg.locator('#ab-open').inner_text())
    pg.click('#ab-open'); pg.wait_for_selector('#ab-play')
    ok('открылся плеер', 'audio-peter' in pg.url and 'Глава 1 из 2' in pg.locator('#ab-where').inner_text())
    ok('4 скорости, «Обычно» выбрана', pg.locator('.chip[data-rate]').count()==4 and pg.locator('.chip[aria-pressed="true"]').inner_text()=='Обычно')
    pg.click('.chip[data-rate="0.6"]'); pg.wait_for_timeout(100)
    pg.evaluate('window.__spoken=[]; window.__rates=[]; const sp=speechSynthesis.speak; speechSynthesis.speak=function(u){ window.__rates.push(u.rate); return sp.call(this,u); }; 0')
    pg.click('#ab-play'); pg.wait_for_function('window.__spoken.length>=2', timeout=5000)
    sp=pg.evaluate('window.__spoken')
    ok('чтение пошло по предложениям', len(sp)>=2 and all(x[0]=='en-US' for x in sp), sp[:3])
    ok('скорость «Медленно» применяется', pg.evaluate('window.__rates').count(0.6)>=1, pg.evaluate('window.__rates')[:3])
    ok('подсвечено текущее предложение', pg.locator('.ab-s.on').count()==1)
    ok('экран не гаснет (wake lock)', pg.evaluate('window.__wake')==1)
    pg.wait_for_function("document.querySelector('#ab-where').textContent.includes('абзац 3')", timeout=8000)
    ok('абзацы идут подряд', True)
    pg.click('#ab-play'); pg.wait_for_timeout(200)
    ok('пауза: звук стоп, wake lock отпущен', pg.locator('.ab-s.on').count()==0 and pg.evaluate('window.__wake')==0)
    where=pg.locator('#ab-where').inner_text()
    pg.click('#ab-next'); pg.wait_for_timeout(100)
    ok('вперёд на абзац', pg.locator('#ab-where').inner_text()!=where, pg.locator('#ab-where').inner_text())
    pg.click('#ab-prev'); pg.wait_for_timeout(100)
    ok('назад на абзац', pg.locator('#ab-where').inner_text()==where)
    # выход и возвращение — продолжение с места
    pg.goto(BASE+'#books'); pg.wait_for_selector('#ab-last')
    ok('на полке «Продолжить слушать»', 'Peter' in pg.locator('#ab-last').inner_text())
    pg.click('#ab-last'); pg.wait_for_selector('#ab-play')
    ok('продолжение с того же абзаца', pg.locator('#ab-where').inner_text()==where and pg.locator('#ab-resume').count()==1, pg.locator('#ab-where').inner_text())
    ok('скорость запомнилась', pg.locator('.chip[aria-pressed="true"]').inner_text()=='Медленно')
    # конец главы 1 → глава 2 сама, глава 1 отмечена прочитанной
    n1=pg.evaluate("BOOKS.find(b=>b.id==='peter').chapters[0].p.length")
    pg.select_option('#ab-ch','0'); pg.wait_for_timeout(100)
    for i in range(n1-1): pg.click('#ab-next')
    ok('последний абзац главы 1', ('абзац %d из %d' % (n1,n1)) in pg.locator('#ab-where').inner_text())
    pg.click('#ab-play')
    pg.wait_for_function("document.querySelector('#ab-where').textContent.includes('Глава 2')", timeout=8000)
    ok('после главы 1 сама началась глава 2', True)
    prog=pg.evaluate("App.kvGet('bookProgress').then(p=>p.peter && p.peter.done)")
    ok('дослушанная глава отмечена прочитанной', prog and 0 in prog, prog)
    pg.click('#ab-play'); pg.wait_for_timeout(100)
    # открыть текст главы
    pg.click('#ab-read'); pg.wait_for_selector('.rw')
    ok('«Открыть текст главы» → чтение главы 2', 'read-peter-1' in pg.url)
    ok('в чтении кнопка «Продолжить слушать»', 'Продолжить слушать' in pg.locator('#ab-open').inner_text())
    # книга из одной главы — из экрана чтения
    pg.goto(BASE+'#read-hen-0'); pg.wait_for_selector('#ab-open')
    ok('в одноглавной книге — «Слушать как аудиокнигу»', 'аудиокнигу' in pg.locator('#ab-open').inner_text())
    pg.click('#ab-open'); pg.wait_for_selector('#ab-play')
    ok('одна глава — без выбора главы', pg.locator('#ab-ch').count()==0 and 'абзац 1 из' in pg.locator('#ab-where').inner_text())
    n=pg.evaluate("BOOKS.find(b=>b.id==='hen').chapters[0].p.length")
    for i in range(n-1): pg.click('#ab-next')
    pg.click('#ab-play')
    pg.wait_for_function("document.querySelector('.toast') && document.querySelector('.toast').textContent.includes('Книга дослушана')", timeout=8000); pg.wait_for_timeout(200)
    pos=pg.evaluate("App.kvGet('audioPos').then(p=>p.hen)")
    ok('книга дослушана — в следующий раз сначала', pos and pos['done'] and pos['ch']==0, pos)
    pg.screenshot(path='/tmp/claude-0/-home-claude-slova/bc44c1c6-67d3-5623-898c-db06ffe2d902/scratchpad/audiobook.png')
    # тихий режим — кнопка неактивна
    pg.evaluate("App.setQuiet(60)"); pg.goto(BASE+'#books'); pg.wait_for_selector('.tile.wide'); pg.goto(BASE+'#audio-hen'); pg.wait_for_selector('#ab-play')
    ok('в тихом режиме плеер не звучит', pg.locator('#ab-play').is_disabled())
    ok('нет «null» в тексте экрана', 'null' not in pg.locator('main').inner_text())
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
