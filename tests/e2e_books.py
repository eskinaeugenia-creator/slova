exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
SH='/tmp/claude-0/-home-claude/de85335f-0f5d-5bd4-b2db-7618e4b0e2be/scratchpad/'
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True, device_scale_factor=2)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    ctx.route('https://api.mymemory.translated.net/**', lambda r: r.fulfill(status=200, content_type='application/json', body='{"responseData":{"translatedText":"ПЕРЕВОД"},"responseStatus":200,"matches":[]}'))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.goto(BASE+'#train'); pg.wait_for_selector('.tile')
    ok('плитка «Книжная полка»', pg.locator('.tile:has-text("Книжная полка")').count()==1)
    pg.click('.tile:has-text("Книжная полка")'); pg.wait_for_selector('.tile.wide')
    ok('8 книг на 5 уровнях', pg.locator('.tile.wide').count()==8 and pg.locator('.section-title').count()==6, pg.locator('.section-title').all_inner_texts())
    pg.screenshot(path=SH+'shelf.png', full_page=False)
    pg.click('.tile.wide:has-text("The Little Red Hen")'); pg.wait_for_selector('.rw')
    ok('одна глава — сразу чтение', 'read-hen-0' in pg.url)
    pg.locator('.rw', has_text='seeds').first.click(); pg.wait_for_selector('.sheet')
    t=pg.locator('.sheet').inner_text()
    ok('seeds → seed, семя', 'seed' in t and 'семя' in t, t[:80])
    ok('слово озвучено', ['en-US','seed'] in pg.evaluate('window.__spoken') or any(s[1]=='seed' for s in pg.evaluate('window.__spoken')))
    pg.screenshot(path=SH+'word.png')
    pg.click('#w-add'); pg.wait_for_timeout(300)
    w=pg.evaluate("(() => { const w=[...App.S.words.values()].find(w=>w.en==='seed'); return w && [w.ru, w.example, App.setName(w.setIds[0])]; })()")
    ok('добавлено в словарь с примером и набором «Из книг»', w and w[0]=='семя' and 'seeds' in w[1] and w[2]=='Из книг', w)
    ok('слово теперь подчёркнуто', pg.locator('.rw.known', has_text='seeds').count()>=1)
    pg.locator('.rw', has_text='finds').first.click(); pg.wait_for_selector('.sheet')
    ok('finds → find, находить', 'находить' in pg.locator('.sheet').inner_text())
    pg.locator('.sheet .icon-btn').click()
    pg.locator('.rw', has_text='says').first.click(); pg.wait_for_selector('.sheet')
    ok('says → say', 'говорить' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.locator('.rp-tools button:has-text("Перевод")').first.click(); pg.wait_for_timeout(200)
    ok('перевод абзаца (свой)', 'курочка' in pg.locator('.rp-tr').first.inner_text())
    pg.evaluate("window.__spoken=[]"); pg.click("#read-play"); pg.wait_for_timeout(300)
    ok('«Слушать всё» читает по фразам и подсвечивает', len(pg.evaluate('window.__spoken'))>=2 and pg.locator('.rp.reading').count()==1)
    pg.click('#read-play'); pg.wait_for_timeout(200)
    ok('стоп', pg.locator('.rp.reading').count()==0)
    pg.locator('.opt').first.wait_for()
    n_q=pg.locator('.options').count()
    for i in range(n_q): pg.locator('.options').nth(i).locator('.opt').first.click()
    ok('вопросы после текста отвечаются', pg.locator('.opt.right').count()==n_q)
    pg.click('#read-done'); pg.wait_for_selector('.tile.wide')
    ok('отметка «прочитано» на полке', pg.locator('.tile.wide:has-text("Red Hen") >> text=прочитано').count()==1)
    # оригинал: Питер, неправильный глагол и онлайн-перевод
    pg.goto(BASE+'#read-alice-0'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='went').first.click(); pg.wait_for_selector('.sheet')
    ok('went → go (идти)', 'идти' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.locator('.rp-tools button:has-text("Перевод")').first.click(); pg.wait_for_timeout(600)
    ok('перевод абзаца оригинала онлайн', 'ПЕРЕВОД' in pg.locator('.rp-tr').first.inner_text())
    # своя книга
    pg.goto(BASE+'#books'); pg.wait_for_selector('#mybook-add'); pg.click('#mybook-add')
