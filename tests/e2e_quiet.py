# Тихий режим: без звука на час, только письменные и выбор ответа, выключается сам
import os
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
SH=os.environ.get('SHOTS', '/home/claude/tests/shots/')
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':375,'height':740}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://commons.wikimedia.org/**', lambda r: r.fulfill(status=500, body='')); ctx.route('https://api.openverse.org/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.goto(BASE+'#set-family'); pg.wait_for_selector('text=Добавить в словарь'); pg.click('text=Добавить в словарь'); pg.wait_for_timeout(600)
    pg.goto(BASE+'#today'); pg.wait_for_selector('#quiet-on')
    ok('на «Сегодня» есть кнопка «Тихий режим»', 'Тихий режим' in pg.locator('#quiet-on').inner_text())
    pg.click('#quiet-on'); pg.wait_for_selector('#quiet-banner')
    left=pg.evaluate("Math.round((App.S.settings.quietUntil - Date.now())/60000)")
    ok('включён на час', 59<=left<=60, left)
    ok('плашка показывает остаток и «Включить звук»', 'ещё 60 мин' in pg.locator('#quiet-banner').inner_text() and pg.locator('#quiet-off').count()==1, pg.locator('#quiet-banner').inner_text())
    pg.screenshot(path=SH+'quiet-today.png')
    pg.click('#quiet-more'); pg.wait_for_selector('#quiet-banner:has-text("ещё 90 мин")', timeout=3000)
    ok('«+30 мин» продлевает', 'ещё 90 мин' in pg.locator('#quiet-banner').inner_text(), pg.locator('#quiet-banner').inner_text())
    # Занятие в тихом режиме: в очереди нет заданий на слух, ничего не звучит
    pg.evaluate("window.__spoken=[]")
    pg.click('text=Начать «Мои'); pg.wait_for_selector('.sbar'); pg.wait_for_timeout(400)
    types=pg.evaluate("App.kvGet('session').then(s => s.queue.map(q => q.type))")
    ok('в занятии нет упражнений на слух', types and not any(t.startswith('listen') for t in types), types)
    ok('в занятии значок 🔇', pg.locator('#quiet-toggle').inner_text()=='🔇')
    pg.wait_for_timeout(500)
    ok('ничего не озвучено', pg.evaluate("window.__spoken.length")==0, pg.evaluate("window.__spoken"))
    pg.evaluate("App.Speech.say('hello')"); pg.wait_for_timeout(100)
    ok('нажатие «озвучить» в тихом режиме молчит', pg.evaluate("window.__spoken.length")==0)
    # Выключить тихий режим прямо в занятии
    pg.click('#quiet-toggle'); pg.wait_for_timeout(300)
    ok('в занятии можно включить звук обратно', pg.evaluate("App.quiet()")==False and pg.locator('#quiet-toggle').inner_text()=='🔊')
    pg.evaluate("Train.abort(true)")
    # Включить посреди задания на слух — задание меняется на выбор перевода
    pg.evaluate("Train.startPrep({ wordIds: App.wordsArr().slice(0,5).map(w=>w.id), types: ['listenChoice'], mode: 'prep', title: 'Проверка' })")
    pg.wait_for_selector('.task'); pg.wait_for_timeout(300)
    t0=pg.locator('.task').first.inner_text()
    pg.click('#quiet-toggle'); pg.wait_for_timeout(300)
    t1=pg.locator('.task').first.inner_text()
    ok('задание на слух → «Выберите перевод»', 'Послушайте' in t0 and 'Выберите перевод' in t1, (t0, t1))
    pg.screenshot(path=SH+'quiet-session.png')
    pg.evaluate("Train.abort(true)")
    # Выключается сам: время вышло
    pg.evaluate("App.S.settings.quietUntil = Date.now() - 1000; App.saveSettings()")
    pg.goto(BASE+'#today'); pg.reload(); pg.wait_for_selector('h1'); pg.wait_for_timeout(300)
    ok('по истечении времени звук возвращается сам', pg.evaluate("App.quiet()")==False and pg.locator('#quiet-banner').count()==0 and pg.locator('#quiet-on').count()==1)
    ok('настройка «Озвучка слов» не тронута', pg.evaluate("App.S.settings.sound")==True)
    ok('нет горизонтальной прокрутки', pg.evaluate("document.documentElement.scrollWidth <= innerWidth"))
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
