# Книги-оригиналы: «The Tale of Benjamin Bunny» (уровень 3, свой перевод), вторые главы Oz и Alice, словарик
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://api.mymemory.translated.net/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.goto(BASE+'#books'); pg.wait_for_selector('.tile.wide')
    titles=pg.locator('.tile.wide b').all_inner_texts()
    ok('Benjamin Bunny на полке', 'The Tale of Benjamin Bunny' in titles, titles)
    ok('Benjamin Bunny сразу после Peter Rabbit', titles.index('The Tale of Benjamin Bunny') == titles.index('The Tale of Peter Rabbit') + 1)
    pg.click('.tile.wide:has-text("Benjamin Bunny")'); pg.wait_for_selector('.tile.wide')
    ok('у Benjamin Bunny 2 части', pg.locator('.tile.wide').count()==2)
    pg.goto(BASE+'#read-benjamin-1'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='forgave').first.click(); pg.wait_for_selector('.sheet')
    ok('forgave → forgive, прощать', 'прощать' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.locator('.rp-tools button:has-text("Перевод")').first.click(); pg.wait_for_timeout(200)
    ok('свой перевод абзаца без интернета', 'Питеру, похоже' in pg.locator('.rp-tr').first.inner_text())
    ok('после части — 3 вопроса', pg.locator('.options').count()==3)
    pg.goto(BASE+'#book-oz'); pg.wait_for_selector('.tile.wide')
    ok('Oz: 6 частей (главы 1–2)', pg.locator('.tile.wide').count()==6)
    pg.goto(BASE+'#read-oz-5'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='kissed').first.click(); pg.wait_for_selector('.sheet')
    ok('kissed → kiss, целовать', 'целовать' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.goto(BASE+'#book-alice'); pg.wait_for_selector('.tile.wide')
    ok('Alice: 6 частей (главы 1–2)', pg.locator('.tile.wide').count()==6)
    pg.goto(BASE+'#read-alice-4'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='swam').first.click(); pg.wait_for_selector('.sheet')
    ok('swam → плыла', 'плыл' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
