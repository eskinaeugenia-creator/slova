# Третьи главы оригиналов: Oz «How Dorothy Saved the Scarecrow» и Alice «A Caucus-Race and a Long Tale», словарик
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
with sync_playwright() as p:
    b=p.chromium.launch(); ctx=b.new_context(viewport={'width':390,'height':800}, is_mobile=True, has_touch=True)
    ctx.add_init_script(FAKE_TTS)
    ctx.route('https://api.mymemory.translated.net/**', lambda r: r.fulfill(status=500, body=''))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.goto(BASE+'#books'); pg.wait_for_selector('.tile.wide')
    ok('Oz на полке: главы 1–3', 'главы 1–3' in pg.locator('.tile.wide:has-text("Wizard of Oz")').inner_text())
    pg.goto(BASE+'#book-oz'); pg.wait_for_selector('.tile.wide')
    ok('Oz: часть «How Dorothy Saved the Scarecrow · part 4»', pg.locator('.tile.wide', has_text='How Dorothy Saved the Scarecrow · part 4').count()==1)
    pg.goto(BASE+'#read-oz-9'); pg.wait_for_selector('.rw')
    ok('последняя часть Oz кончается на «lighted match»', 'lighted match' in pg.locator('body').inner_text())
    pg.locator('.rw', has_text='brains').first.click(); pg.wait_for_selector('.sheet')
    ok('brains → brain, мозг', 'мозг' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    ok('после части — 2 вопроса', pg.locator('.options').count()==2)
    pg.goto(BASE+'#read-alice-7'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='thimble').first.click(); pg.wait_for_selector('.sheet')
    ok('thimble → напёрсток', 'напёрсток' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    pg.goto(BASE+'#read-alice-8'); pg.wait_for_selector('.rw')
    pg.locator('.rw', has_text='tale').first.click(); pg.wait_for_selector('.sheet')
    ok('tale — история (и tail — хвост)', 'хвост' in pg.locator('.sheet').inner_text()); pg.locator('.sheet .icon-btn').click()
    ok('нет ошибок на странице', not errs, errs)
    print(f'Итог: {sum(res)} из {len(res)}')
