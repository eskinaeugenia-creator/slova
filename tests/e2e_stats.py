# «Автор видит, кто занимается»: только с согласия, без адреса таблицы — ничего не видно и не отправляется
import json
exec(open('tests/e2e_extra.py', encoding='utf-8').read().split('with sync_playwright()')[0])
URL='https://script.google.com/macros/s/TEST/exec'
with sync_playwright() as p:
    b=p.chromium.launch()
    # 1) адрес не задан — карточки нет, в Настройках пусто, запросов нет
    ctx=b.new_context(viewport={'width':390,'height':800}); ctx.add_init_script(FAKE_TTS)
    sent=[]; ctx.route('https://script.google.com/**', lambda r: (sent.append(r.request.post_data), r.fulfill(status=200, body='ok')))
    pg=ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.evaluate("(async()=>{ App.S.settings.levelSkip=true; App.S.settings.name='Аня'; await App.saveSettings(); App.routes.today(); })()"); pg.wait_for_timeout(300)
    ok('без адреса таблицы вопроса нет', pg.locator('#stats-offer').count()==0)
    pg.goto(BASE+'#prefs'); pg.wait_for_timeout(400)
    ok('без адреса таблицы в Настройках пусто', pg.locator('#stats-prefs').count()==0)
    ok('без адреса ничего не отправлено', not sent, sent)
    ctx.close()
    # 2) адрес задан
    ctx=b.new_context(viewport={'width':390,'height':800}); ctx.add_init_script(FAKE_TTS); ctx.add_init_script(f"window.STATS_URL_OVERRIDE={URL!r};")
    sent=[]; ctx.route('https://script.google.com/**', lambda r: (sent.append(r.request.post_data), r.fulfill(status=200, body='ok')))
    pg=ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.evaluate("(async()=>{ App.S.settings.levelSkip=true; App.S.settings.name='Аня'; await App.saveSettings(); const w=App.newWord({en:'secretword',ru:'тайна'}); await App.saveWord(w); App.routes.today(); })()")
    pg.wait_for_selector('#stats-offer')
    ok('вопрос «Можно Евгении видеть…» на «Сегодня»', 'Можно Евгении видеть' in pg.locator('#stats-offer').inner_text())
    pg.wait_for_timeout(4500)
    ok('до ответа ничего не отправлено', not sent, sent)
    pg.click('#stats-yes'); pg.wait_for_timeout(800)
    ok('после «Да» отправлена одна строка', len(sent)==1, len(sent))
    d=json.loads(sent[0]) if sent else {}
    ok('в строке имя, число слов, дата первого входа, версия', d.get('name')=='Аня' and d.get('words')==1 and d.get('first',0)>1e12 and d.get('v') and d.get('id','').startswith('web-'), d)
    ok('сами слова не отправляются', 'secretword' not in (sent[0] or '') and 'тайна' not in (sent[0] or ''))
    ok('вопрос больше не показывается', pg.locator('#stats-offer').count()==0)
    pg.evaluate("Stats.send()"); pg.wait_for_timeout(500)
    ok('повторно в течение 6 часов не отправляется', len(sent)==1, len(sent))
    pg.goto(BASE+'#prefs'); pg.wait_for_selector('#stats-prefs')
    ok('в Настройках включено', pg.locator('#stats-share').is_checked())
    pg.locator('#stats-prefs .switch').click(); pg.wait_for_timeout(600)
    ok('выключили — отправлена просьба удалить строку', len(sent)==2 and json.loads(sent[1]).get('optout') is True and json.loads(sent[1])['id']==d.get('id'), sent[1:])
    ok('согласие снято', pg.evaluate("App.S.settings.shareStats")==False)
    pg.evaluate("Stats.send(true)"); pg.wait_for_timeout(400)
    ok('без согласия не отправляется даже принудительно', len(sent)==2)
    ctx.close()
    # 3) «Нет» — ничего не отправляется
    ctx=b.new_context(viewport={'width':390,'height':800}); ctx.add_init_script(FAKE_TTS); ctx.add_init_script(f"window.STATS_URL_OVERRIDE={URL!r};")
    sent=[]; ctx.route('https://script.google.com/**', lambda r: (sent.append(r.request.post_data), r.fulfill(status=200, body='ok')))
    pg=ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(BASE); pg.wait_for_selector('h1')
    pg.evaluate("(async()=>{ App.S.settings.levelSkip=true; await App.saveSettings(); App.routes.today(); })()"); pg.wait_for_selector('#stats-offer')
    pg.click('#stats-no'); pg.wait_for_timeout(500)
    ok('после «Нет» ничего не отправлено и вопрос скрыт', not sent and pg.locator('#stats-offer').count()==0, sent)
    ok('нет ошибок на странице', not errs, errs)
